def process_pdf(file_path, doc_id, thread_id, parent_id, filename):
    use_opendataloader = _should_use_opendataloader_pdf()
    if use_opendataloader:
        if not OPENDATALOADER_PDF_AVAILABLE:
            if RAG_PDF_EXTRACTOR in {"opendataloader", "opendataloader-pdf", "openpdf"}:
                raise RuntimeError(
                    "RAG_PDF_EXTRACTOR requires OpenDataLoader, but package is missing. "
                    "Install with: pip install opendataloader-pdf"
                )
            print("[RAG] OpenDataLoader not installed; using PyMuPDF fallback")
        else:
            try:
                return process_pdf_with_opendataloader(file_path, doc_id, thread_id, parent_id, filename)
            except Exception as exc:
                if RAG_PDF_EXTRACTOR in {"opendataloader", "opendataloader-pdf", "openpdf"}:
                    raise
                print(f"[RAG] OpenDataLoader ingestion failed ({exc}); falling back to PyMuPDF")

    # Ensure model is loaded
    if not model_manager.is_ready():
        model_manager.load_model()

    if not model_manager.is_ready():
        raise RuntimeError("Embedding model not configured. Please set model path in Settings.")

    start_time = time.time()
    process = psutil.Process()
    start_memory = process.memory_info().rss / 1024 / 1024  # MB
    start_cpu = process.cpu_percent(interval=0.1)

    print(f"\n[RAG] Processing PDF: {filename} (Doc ID: {doc_id})")
    doc = fitz.open(file_path)

    text_chunks = []
    metadatas = []
    ids = []
    table_embeddings = []  # Store table data for embedding
    table_count = 0
    chunk_count = 0
    total_pages = len(doc)

    # Multi-page table tracking
    previous_table = None
    merged_table_count = 0

    print(f"[RAG] Processing {total_pages} pages...")

    for page_num, page in enumerate(doc):
        # Extract text chunks
        text = page.get_text()
        chunks = smart_chunk_text(text)
        chunk_count += len(chunks)

        for i, chunk in enumerate(chunks):
            chunk_id = f"{doc_id}_{page_num}_{i}"
            text_chunks.append(chunk)
            ids.append(chunk_id)

            metadatas.append({
                "doc_id": str(doc_id),
                "thread_id": str(thread_id),
                "parent_id": str(parent_id) if parent_id else "none",
                "source": filename,
                "page": page_num + 1,
                "type": "text"
            })

        # Extract tables from the page
        tables = extract_tables_from_page(page)
        if tables:
            for table_idx, table in enumerate(tables):
                # Check if this is a continuation of the previous table
                is_continuation = False
                if previous_table and table_idx == 0:  # Only check first table on page
                    is_continuation = is_table_continuation(previous_table, table)
                
                if is_continuation:
                    # Merge with previous table
                    print(f"[RAG] Detected table continuation on page {page_num + 1} (merging...)")
                    incoming_rows = table['data']
                    if previous_table['headers'] and table.get('headers'):
                        prev_headers = [_clean_table_cell(h) for h in previous_table['headers']]
                        curr_headers = [_clean_table_cell(h) for h in table['headers']]
                        if prev_headers and prev_headers == curr_headers and len(incoming_rows) > 1:
                            # Avoid duplicating repeated header row on paginated tables.
                            incoming_rows = incoming_rows[1:]

                    previous_table['data'].extend(incoming_rows)
                    previous_table['row_count'] += table['row_count']
                    if (page_num + 1) not in previous_table['pages']:
                        previous_table['pages'].append(page_num + 1)
                    merged_table_count += 1
                    # Don't store yet, wait for actual end
                    continue
                else:
                    # Store any accumulated previous table
                    if previous_table:
                        table_data = _store_merged_table(
                            previous_table, doc_id, thread_id, parent_id, filename
                        )
                        table_embeddings.append(table_data)
                        table_count += 1
                    
                    # Start tracking new table
                    previous_table = {
                        'data': table['data'],
                        'headers': table['headers'],
                        'row_count': table['row_count'],
                        'column_count': table['column_count'],
                        'start_page': page_num + 1,
                        'pages': [page_num + 1],
                        'index': table['index'],
                        'page_num': page_num  # Store page number for table_id generation
                    }

        # Print progress every 100 pages
        if (page_num + 1) % 100 == 0 or (page_num + 1) == total_pages:
            print(f"[RAG] Progress: {page_num + 1}/{total_pages} pages | {chunk_count} chunks | {table_count} tables")

    # Store any remaining accumulated table
    if previous_table:
        table_data = _store_merged_table(
            previous_table, doc_id, thread_id, parent_id, filename
        )
        table_embeddings.append(table_data)
        table_count += 1

    doc.close()

    if merged_table_count > 0:
        print(f"[RAG] ✓ Merged {merged_table_count} table continuations across pages")

    # Add table content to chunks for embedding in ChromaDB
    if table_embeddings:
        print(f"[RAG] Adding {len(table_embeddings)} tables to ChromaDB for semantic search")
        for table_data in table_embeddings:
            text_chunks.append(table_data['text'])
            metadatas.append(table_data['metadata'])
            ids.append(table_data['id'])

    if not text_chunks:
        print("[RAG] No valid text chunks found.")
        return {"text_chunks": 0, "table_chunks": table_count}

    print(f"[RAG] Embedding {len(text_chunks)} chunks...")
    embed_start = time.time()
    embeddings = model_manager.encode(text_chunks).tolist()
    embed_time = time.time() - embed_start
    print(f"[RAG] ✓ Embedded in {embed_time:.2f}s")

    # Batch insert to handle large documents (ChromaDB has ~5461 limit per add())
    db_start = time.time()
    total_chunks = len(text_chunks)

    if total_chunks <= CHROMA_BATCH_SIZE:
        # Single batch insert
        collection.add(
            documents=text_chunks,
            embeddings=embeddings,
            metadatas=metadatas,
            ids=ids
        )
    else:
        # Multiple batch inserts
        for i in range(0, total_chunks, CHROMA_BATCH_SIZE):
            end_idx = min(i + CHROMA_BATCH_SIZE, total_chunks)
            batch_docs = text_chunks[i:end_idx]
            batch_embeds = embeddings[i:end_idx]
            batch_metas = metadatas[i:end_idx]
            batch_ids = ids[i:end_idx]

            collection.add(
                documents=batch_docs,
                embeddings=batch_embeds,
                metadatas=batch_metas,
                ids=batch_ids
            )

    db_time = time.time() - db_start
    end_time = time.time()

    text_only_chunks = len(text_chunks) - len(table_embeddings)
    print(f"[RAG] ✓ Completed in {end_time - start_time:.1f}s | {text_only_chunks} text chunks + {table_count} tables embedded in ChromaDB")
    return {"text_chunks": len(text_chunks), "table_chunks": table_count}


