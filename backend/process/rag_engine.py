class EmbeddingModelManager:
    """
    Singleton manager for embedding model with lazy loading and configurable path.
    Model is only loaded when needed and can be reloaded with a different path.
    """
    _instance = None
    _lock = threading.Lock()

    def __new__(cls):
        if cls._instance is None:
            with cls._lock:
                if cls._instance is None:
                    cls._instance = super().__new__(cls)
                    cls._instance._initialized = False
        return cls._instance

    def __init__(self):
        if self._initialized:
            return
        self._model = None
        self._model_path = None
        self._provider_type = None  # 'sentence-transformers' or 'ollama'
        self._ollama_model_name = None
        self._device = "cuda" if CUDA_AVAILABLE else "cpu"
        self._status = {
            "loaded": False,
            "provider": None,
            "path": None,
            "error": None,
            "device": self._device
        }
        self._initialized = True

        if CUDA_AVAILABLE:
            print(f"[RAG] CUDA Available: {torch.cuda.get_device_name(0)}")
            print(f"[RAG] CUDA Memory: {torch.cuda.get_device_properties(0).total_memory / 1024**3:.1f} GB")
        else:
            print("[RAG] Running on CPU (CUDA not available)")

    def _get_provider_type_from_db(self):
        """Get embedding provider type from database."""
        try:
            from .models import AppConfig
            return AppConfig.get_value('embedding_provider', DEFAULT_EMBEDDING_PROVIDER)
        except Exception as e:
            print(f"[RAG] Could not read provider type from DB: {e}")
            return DEFAULT_EMBEDDING_PROVIDER
    
    def _get_model_path_from_db(self):
        """Get model path from database configuration"""
        try:
            from .models import AppConfig
            provider = self._get_provider_type_from_db()
            if provider == 'ollama':
                return AppConfig.get_value('ollama_embedding_model', DEFAULT_OLLAMA_EMBEDDING_MODEL)
            return AppConfig.get_value('embedding_model_path', None)
        except Exception as e:
            print(f"[RAG] Could not read model path from DB: {e}")
            return None

    def _get_default_model_path(self):
        """Get default model path based on provider type."""
        provider = self._get_provider_type_from_db()
        if provider == 'ollama':
            return DEFAULT_OLLAMA_EMBEDDING_MODEL
        return DEFAULT_EMBEDDING_MODEL

    def load_model(self, model_path=None, provider_type=None, force_reload=False):
        """
        Load the embedding model from specified path or Ollama.

        Args:
            model_path: Path to model directory (sentence-transformers) or model name (ollama)
            provider_type: 'sentence-transformers' or 'ollama'. If None, reads from DB.
            force_reload: If True, reloads even if already loaded.

        Returns:
            bool: True if model loaded successfully
        """
        with self._lock:
            # Determine provider type
            if provider_type is None:
                provider_type = self._get_provider_type_from_db()
            
            # Determine which path/model to use
            if model_path is None:
                model_path = self._get_model_path_from_db()

            if model_path is None:
                model_path = self._get_default_model_path()
            
            # Handle Ollama provider
            if provider_type == 'ollama':
                return self._load_ollama_model(model_path, force_reload)

            # Convert relative paths to absolute
            if model_path and not os.path.isabs(model_path):
                # Get project root (two levels up from backend/process/)
                backend_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                project_root = os.path.dirname(backend_dir)
                model_path = os.path.normpath(os.path.join(project_root, model_path))
                print(f"[RAG] Resolved relative path to: {model_path}")

            # Check if we need to reload
            if self._model is not None and self._model_path == model_path and not force_reload:
                return True

            # Check if it's a HuggingFace model name (allow auto-download)
            is_hf_model = '/' in model_path or (not os.path.isabs(model_path) and not os.path.exists(model_path))

            # Validate local path exists (skip for HuggingFace model names)
            if not is_hf_model and not os.path.exists(model_path):
                self._status = {
                    "loaded": False,
                    "path": model_path,
                    "error": f"Model path does not exist: {model_path}",
                    "device": self._device
                }
                print(f"[RAG] ERROR: Model path does not exist: {model_path}")
                return False

            # Check for required model files (skip for HuggingFace model names)
            if not is_hf_model:
                required_files = ["config.json"]
                missing_files = [f for f in required_files if not os.path.exists(os.path.join(model_path, f))]
                if missing_files:
                    self._status = {
                        "loaded": False,
                        "path": model_path,
                        "error": f"Invalid model directory. Missing files: {missing_files}",
                        "device": self._device
                    }
                    print(f"[RAG] ERROR: Invalid model directory. Missing: {missing_files}")
                    return False

            try:
                print(f"[RAG] Loading embedding model from: {model_path}")
                start_time = time.time()

                # Unload previous model to free memory
                if self._model is not None:
                    del self._model
                    self._model = None
                    if CUDA_AVAILABLE:
                        torch.cuda.empty_cache()

                self._model = SentenceTransformer(model_path, device=self._device)
                self._model_path = model_path
                self._provider_type = 'sentence-transformers'

                load_time = time.time() - start_time
                self._status = {
                    "loaded": True,
                    "provider": "sentence-transformers",
                    "path": model_path,
                    "error": None,
                    "device": self._device,
                    "load_time": round(load_time, 2)
                }

                print(f"[RAG] [OK] Embedding model loaded on {self._device.upper()} in {load_time:.2f}s")
                return True

            except Exception as e:
                self._status = {
                    "loaded": False,
                    "provider": "sentence-transformers",
                    "path": model_path,
                    "error": str(e),
                    "device": self._device
                }
                print(f"[RAG] ERROR loading model: {e}")
                return False
    
    def _load_ollama_model(self, model_name, force_reload=False):
        """Load Ollama embedding model."""
        # Check if already loaded
        if (self._model is not None and 
            self._provider_type == 'ollama' and 
            self._ollama_model_name == model_name and 
            not force_reload):
            return True
        
        try:
            print(f"[RAG] Loading Ollama embedding model: {model_name}")
            start_time = time.time()
            
            # Unload previous model
            if self._model is not None:
                del self._model
                self._model = None
            
            self._model = OllamaEmbeddingProvider(model_name)
            self._ollama_model_name = model_name
            self._provider_type = 'ollama'
            
            load_time = time.time() - start_time
            self._status = {
                "loaded": True,
                "provider": "ollama",
                "model": model_name,
                "path": OLLAMA_EMBED_API,
                "error": None,
                "device": "api",
                "load_time": round(load_time, 2)
            }
            
            print(f"[RAG] [OK] Ollama embedding model ready: {model_name}")
            return True
            
        except Exception as e:
            self._status = {
                "loaded": False,
                "provider": "ollama",
                "model": model_name,
                "error": str(e),
                "device": "api"
            }
            print(f"[RAG] ERROR loading Ollama model: {e}")
            return False

    def get_model(self):
        """
        Get the embedding model, loading it if necessary.

        Returns:
            SentenceTransformer or None if not available
        """
        if self._model is None:
            self.load_model()
        return self._model

    def get_status(self):
        """Get current model status"""
        return self._status.copy()

    def is_ready(self):
        """Check if model is loaded and ready"""
        return self._model is not None

    def encode(self, texts):
        """
        Encode texts to embeddings with batch processing optimization.

        Args:
            texts: List of strings to encode

        Returns:
            List of embeddings

        Raises:
            RuntimeError if model not loaded
        """
        model = self.get_model()
        if model is None:
            raise RuntimeError("Embedding model not loaded. Please configure model path in Settings.")

        # Optimize with batch processing for large documents
        if len(texts) > EMBEDDING_BATCH_SIZE:
            return model.encode(texts, batch_size=EMBEDDING_BATCH_SIZE, show_progress_bar=False)
        else:
            return model.encode(texts, show_progress_bar=False)


