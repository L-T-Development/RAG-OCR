def _truncate_text_for_ollama(text, max_chars, label="input"):
    """Best-effort character cap to avoid Ollama context overflow errors."""
    if text is None:
        return ""
    text = str(text)
    if len(text) <= max_chars:
        return text

    print(f"[OLLAMA] Truncating {label}: {len(text)} -> {max_chars} chars")
    if max_chars < 1200:
        suffix = "\n... (truncated to fit model context)"
        if max_chars <= len(suffix):
            return text[:max_chars]
        return text[:max_chars - len(suffix)] + suffix

    marker = "\n\n... (middle content truncated to fit model context) ...\n\n"
    available_chars = max_chars - len(marker)
    if available_chars <= 2:
        return text[:max_chars]

    head_chars = max(1, int(available_chars * 0.55))
    tail_chars = max(1, available_chars - head_chars)
    return (
        text[:head_chars]
        + marker
        + text[-tail_chars:]
    )


