class OllamaEmbeddingProvider:
    """Embedding provider using Ollama API for nomic-embed-text and other models."""
    
    def __init__(self, model_name="nomic-embed-text", api_url=OLLAMA_EMBED_API):
        self.model_name = model_name
        self.api_url = api_url
        self._adaptive_embed_lock = threading.Lock()
        self._adaptive_embed_max_chars = max(
            OLLAMA_EMBED_MIN_CHARS,
            min(OLLAMA_EMBED_MAX_CHARS, OLLAMA_EMBED_START_CHARS)
        )
        self._test_connection()
    
    def _test_connection(self):
        """Test if Ollama is available and model exists."""
        try:
            response = requests.post(
                self.api_url,
                json={"model": self.model_name, "prompt": "test"},
                timeout=10
            )
            if response.status_code != 200:
                print(f"[OLLAMA] Warning: Model {self.model_name} may not be available (status {response.status_code})")
        except requests.exceptions.RequestException as e:
            print(f"[OLLAMA] Warning: Cannot connect to Ollama at {self.api_url}: {e}")

    def _get_current_embed_max_chars(self):
        with self._adaptive_embed_lock:
            return self._adaptive_embed_max_chars

    def _shrink_embed_max_chars(self, new_max_chars):
        with self._adaptive_embed_lock:
            self._adaptive_embed_max_chars = max(
                OLLAMA_EMBED_MIN_CHARS,
                min(self._adaptive_embed_max_chars, new_max_chars)
            )

    def _maybe_grow_embed_max_chars(self):
        if not OLLAMA_EMBED_ALLOW_GROWTH:
            return
        with self._adaptive_embed_lock:
            if self._adaptive_embed_max_chars < OLLAMA_EMBED_MAX_CHARS:
                self._adaptive_embed_max_chars = min(
                    OLLAMA_EMBED_MAX_CHARS,
                    self._adaptive_embed_max_chars + 128
                )

    def _fallback_embedding(self):
        return [0.0] * self.get_dimension()

    def _encode_single_text(self, text):
        try:
            attempt = 0
            current_max_chars = self._get_current_embed_max_chars()

            while attempt < OLLAMA_EMBED_MAX_RETRIES and current_max_chars >= OLLAMA_EMBED_MIN_CHARS:
                label = "embedding input" if attempt == 0 else f"embedding retry #{attempt}"
                safe_text = _truncate_text_for_ollama(text, current_max_chars, label=label)
                try:
                    response = requests.post(
                        self.api_url,
                        json={"model": self.model_name, "prompt": safe_text},
                        timeout=OLLAMA_EMBED_TIMEOUT_SECONDS
                    )
                except requests.exceptions.Timeout:
                    attempt += 1
                    print(
                        f"[OLLAMA] Embedding timeout after {OLLAMA_EMBED_TIMEOUT_SECONDS}s "
                        f"(attempt {attempt}/{OLLAMA_EMBED_MAX_RETRIES})"
                    )
                    if attempt < OLLAMA_EMBED_MAX_RETRIES:
                        continue
                    break

                if response.status_code == 200:
                    result = response.json()
                    embedding = result.get('embedding', [])
                    if embedding:
                        if current_max_chars < self._get_current_embed_max_chars():
                            self._shrink_embed_max_chars(current_max_chars)
                        elif attempt == 0:
                            self._maybe_grow_embed_max_chars()
                        return embedding

                    print(f"[OLLAMA] Warning: Empty embedding for text: {text[:50]}...")
                    break

                if response.status_code == 500 and _is_context_length_error(response.text):
                    next_max = max(OLLAMA_EMBED_MIN_CHARS, int(current_max_chars * 0.6))
                    if next_max == current_max_chars:
                        next_max = current_max_chars - 1
                    print(f"[OLLAMA] Context overflow during embedding; reducing input {current_max_chars} -> {next_max} chars")
                    current_max_chars = next_max
                    self._shrink_embed_max_chars(current_max_chars)
                    attempt += 1
                    continue

                print(f"[OLLAMA] Error {response.status_code}: {response.text}")
                break

        except Exception as e:
            print(f"[OLLAMA] Encoding error: {e}")

        return self._fallback_embedding()
    
    def encode(self, texts, batch_size=32, show_progress_bar=False):
        """Encode texts to embeddings using Ollama API.
        
        Args:
            texts: List of strings or single string to encode
            batch_size: Number of texts to process at once
            show_progress_bar: Ignored (for compatibility with SentenceTransformer)
        
        Returns:
            numpy array of embeddings
        """
        import numpy as np
        
        # Handle single string input
        if isinstance(texts, str):
            texts = [texts]
        
        embeddings = []
        total = len(texts)
        if total == 0:
            return np.array(embeddings)

        processed = 0
        started_at = time.time()
        progress_every = max(1, OLLAMA_EMBED_PROGRESS_EVERY)
        max_workers = min(total, max(1, min(batch_size, OLLAMA_EMBED_PARALLELISM)))
        print(f"[OLLAMA] Embedding with {max_workers} parallel worker(s)")

        ordered_embeddings = [None] * total
        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            future_to_index = {
                executor.submit(self._encode_single_text, text): idx
                for idx, text in enumerate(texts)
            }

            for future in as_completed(future_to_index):
                idx = future_to_index[future]
                try:
                    ordered_embeddings[idx] = future.result()
                except Exception as e:
                    print(f"[OLLAMA] Encoding worker error: {e}")
                    ordered_embeddings[idx] = self._fallback_embedding()

                processed += 1
                if processed % progress_every == 0 or processed == total:
                    elapsed = max(0.001, time.time() - started_at)
                    rate = processed / elapsed
                    remaining = max(0.0, (total - processed) / rate) if rate > 0 else 0.0
                    print(
                        f"[OLLAMA] Embedding progress: {processed}/{total} "
                        f"({rate:.2f} chunks/s, ETA ~{remaining:.0f}s)"
                    )

                if show_progress_bar and processed % 100 == 0:
                    print(f"[OLLAMA] Encoded {processed}/{total} texts")

        embeddings.extend(ordered_embeddings)
        return np.array(embeddings)
    
    def get_dimension(self):
        """Get embedding dimension (768 for nomic-embed-text)."""
        if "nomic" in self.model_name.lower():
            return 768
        return 384  # Default fallback

