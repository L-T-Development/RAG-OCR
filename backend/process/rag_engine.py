def _markdown_table_to_rows(markdown_text):
    """Parse markdown table text into row arrays."""
    rows = []
    if not markdown_text:
        return rows

    for raw_line in str(markdown_text).splitlines():
        line = raw_line.strip()
        if not line or "|" not in line:
            continue

        normalized = line.strip("|")
        if not normalized:
            continue

        # Skip separator rows like |---|:---:|
        separator_candidate = normalized.replace(" ", "")
        if separator_candidate and set(separator_candidate) <= {"-", ":", "|"}:
            continue

        cells = [_clean_table_cell(cell) for cell in normalized.split("|")]
        if any(cells):
            rows.append(cells)

    return rows


def _extract_text_from_od_element(element):
    """Extract human-readable text from an OpenDataLoader element."""
    for key in ("content", "text", "markdown", "description"):
        value = element.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()

    rows = _extract_table_rows_from_od_element(element)
    if rows:
        return "\n".join(" | ".join(str(cell) for cell in row if cell) for row in rows)

    return ""


def _extract_table_rows_from_od_element(element):
    """Best-effort extraction of table rows from OpenDataLoader JSON element."""
    direct_rows = element.get("data")
    if isinstance(direct_rows, list) and direct_rows and isinstance(direct_rows[0], list):
        return direct_rows

    table_obj = element.get("table")
    if isinstance(table_obj, dict):
        rows = table_obj.get("rows") or table_obj.get("data")
        if isinstance(rows, list) and rows and isinstance(rows[0], list):
            return rows

    markdown = element.get("markdown") or element.get("content")
    markdown_rows = _markdown_table_to_rows(markdown)
    if markdown_rows:
        return markdown_rows

    return []


