def _clean_table_cell(value):
    """Normalize table cell content for de-duplication and quality checks."""
    if value is None:
        return ""
    cleaned = re.sub(r"\s+", " ", str(value).replace("\x00", " ")).strip()
    if cleaned in {"|", "-"}:
        return ""
    return cleaned


def _normalize_table_rows(table_data):
    """Clean rows, remove empty rows, and align row width for downstream parsing."""
    normalized_rows = []
    max_cols = 0

    for row in table_data or []:
        if not isinstance(row, (list, tuple)):
            continue
        cleaned_row = [_clean_table_cell(cell) for cell in row]

        # Remove trailing empty cells frequently introduced by table detectors.
        while cleaned_row and not cleaned_row[-1]:
            cleaned_row.pop()

        if any(cleaned_row):
            normalized_rows.append(cleaned_row)
            max_cols = max(max_cols, len(cleaned_row))

    if not normalized_rows or max_cols == 0:
        return []

    return [row + [""] * (max_cols - len(row)) for row in normalized_rows]


def _is_probable_header_row(row):
    """Heuristic to decide whether the first row is header text."""
    if not row:
        return False

    non_empty = [cell for cell in row if cell]
    if not non_empty:
        return False

    alpha_cells = sum(1 for cell in non_empty if re.search(r"[A-Za-z]", cell))
    numeric_like_cells = sum(1 for cell in non_empty if re.fullmatch(r"[\d\s.,:%/()\-]+", cell))
    unique_ratio = len({cell.lower() for cell in non_empty}) / max(len(non_empty), 1)

    return (
        alpha_cells >= max(1, len(non_empty) // 2)
        and numeric_like_cells < len(non_empty)
        and unique_ratio >= 0.5
    )


def _extract_headers_and_rows(normalized_rows):
    """Split normalized table rows into headers and data rows."""
    if not normalized_rows:
        return [], []

    if len(normalized_rows) >= 2 and _is_probable_header_row(normalized_rows[0]):
        headers = normalized_rows[0]
        rows = normalized_rows[1:]

        # Drop repeated header rows inside paginated tables.
        while rows and rows[0] == headers:
            rows = rows[1:]

        return headers, rows

    return [], normalized_rows


def _table_signature(table_data):
    """Create a stable signature for table de-duplication within a page."""
    normalized_rows = []
    for row in _normalize_table_rows(table_data):
        if not isinstance(row, (list, tuple)):
            continue
        normalized_row = [_clean_table_cell(cell) for cell in row]
        normalized_rows.append(tuple(normalized_row))
    return tuple(normalized_rows)


def _has_meaningful_table_content(table_data):
    """Reject empty/near-empty table candidates frequently produced by detectors."""
    normalized_rows = _normalize_table_rows(table_data)
    if not normalized_rows:
        return False

    meaningful_cells = 0
    rows_with_content = 0

    for row in normalized_rows:
        if not isinstance(row, (list, tuple)):
            continue
        row_has_content = False
        for cell in row:
            if _clean_table_cell(cell):
                meaningful_cells += 1
                row_has_content = True
        if row_has_content:
            rows_with_content += 1

    if rows_with_content == 1:
        # Allow compact key-value style tables with a single useful row.
        return meaningful_cells >= 2

    # Require at least a small amount of actual text content.
    return rows_with_content >= 2 and meaningful_cells >= 4


def _is_context_length_error(error_text):
    if not error_text:
        return False
    lowered = str(error_text).lower()
    return "input length exceeds the context length" in lowered or "context length" in lowered


def _safe_ollama_generate(payload, timeout=90):
    """Call Ollama generate API with automatic context-overflow fallback."""
    request_payload = dict(payload)
    request_payload["prompt"] = _truncate_text_for_ollama(
        request_payload.get("prompt", ""),
        OLLAMA_PROMPT_MAX_CHARS,
        label="prompt"
    )

    if request_payload.get("system"):
        request_payload["system"] = _truncate_text_for_ollama(
            request_payload["system"],
            4000,
            label="system prompt"
        )

    for attempt in range(2):
        http_response = requests.post(OLLAMA_API, json=request_payload, timeout=timeout)

        if http_response.status_code != 200:
            body = http_response.text
            if attempt == 0 and _is_context_length_error(body):
                current_prompt = request_payload.get("prompt", "")
                reduced_len = max(1000, len(current_prompt) // 2)
                print(f"[OLLAMA] Context overflow from API status {http_response.status_code}; retrying with {reduced_len} chars")
                request_payload["prompt"] = _truncate_text_for_ollama(current_prompt, reduced_len, label="retry prompt")
                continue
            return {"error": f"HTTP {http_response.status_code}: {body}"}

        try:
            response_json = http_response.json()
        except json.JSONDecodeError as exc:
            return {"error": f"Invalid JSON response from Ollama: {exc}"}

        ollama_error = response_json.get("error")
        if attempt == 0 and _is_context_length_error(ollama_error):
            current_prompt = request_payload.get("prompt", "")
            reduced_len = max(1000, len(current_prompt) // 2)
            print(f"[OLLAMA] Context overflow in JSON response; retrying with {reduced_len} chars")
            request_payload["prompt"] = _truncate_text_for_ollama(current_prompt, reduced_len, label="retry prompt")
            continue

        return response_json

    return {"error": "Ollama context overflow after retries"}


